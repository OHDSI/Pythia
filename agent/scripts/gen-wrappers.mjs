#!/usr/bin/env -S deno run --allow-read --allow-write
// Generates agent/plugin/agent/tools/<name>.js — one trex-eve tool wrapper
// per pythia.agent-tools/tools entry — plus a copy of the compiled bundle at
// agent/plugin/agent/tools/_build/tools.js.
//
// Run under deno with the eve/tools stub import map (see
// scripts/import-map.deno.json) because out/tools.js (the shadow-cljs
// release build of the :tools module) is Closure-compiled ESM with a bare
// `import ... from "eve/tools"` left in place (:keep-as-import) — that
// import only resolves via an import map, and the Closure output is not
// guaranteed to run under plain node. In production the trex agents runtime
// supplies its own eve/tools shim at the same bare specifier (see
// core/server/plugin/agents.ts); this script's stub is a TEST-TIME stand-in
// used only to read `Object.keys(tools)` and each tool's shape, matching how
// agent/test/eve_tools_stub.mjs is already used for shadow-cljs's :test build.
//
// Directories under tools/ (namely _build/) are invisible to the trex loader
// (core/server/agents/loader.ts only reads *.{ts,js,mts,mjs} FILES directly
// in tools/), so nesting the bundle at tools/_build/tools.js is safe.
import { tools } from "../out/tools.js";

const EXPECTED_TOOL_COUNT = 55;

const names = Object.keys(tools);
if (names.length !== EXPECTED_TOOL_COUNT) {
  console.error(
    `gen-wrappers: expected ${EXPECTED_TOOL_COUNT} tools from out/tools.js, got ${names.length}: ${
      names.join(", ")
    }`,
  );
  Deno.exit(1);
}

const outDir = new URL("../plugin/agent/tools/", import.meta.url);
const buildDir = new URL("_build/", outDir);
await Deno.mkdir(buildDir, { recursive: true });

// Clear stale wrapper files from a previous run (e.g. a tool that was
// removed) before regenerating — everything directly under tools/ except
// the _build/ directory is generated output.
for await (const entry of Deno.readDir(outDir)) {
  if (entry.isFile && /\.(js|mjs)$/.test(entry.name)) {
    await Deno.remove(new URL(entry.name, outDir));
  }
}

await Deno.copyFile(new URL("../out/tools.js", import.meta.url), new URL("tools.js", buildDir));

for (const name of names) {
  const content = `// generated by scripts/gen-wrappers.mjs — do not edit
globalThis.__pythiaModuleUrl ??= import.meta.url;
import { tools } from "./_build/tools.js";
export default tools["${name}"];
`;
  await Deno.writeTextFile(new URL(`${name}.js`, outDir), content);
}

console.log(`gen-wrappers: wrote ${names.length} tool wrappers + _build/tools.js`);
